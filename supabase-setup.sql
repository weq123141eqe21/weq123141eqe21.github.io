-- 在 Supabase 的 SQL Editor 中执行一次即可。

create table if not exists public.votes (
  id bigint generated by default as identity primary key,
  choice text not null check (choice in ('A','B','C','D')),
  device_id text not null unique,
  created_at timestamptz not null default now()
);

alter table public.votes enable row level security;

drop policy if exists "public can read votes" on public.votes;
create policy "public can read votes"
on public.votes
for select
to anon
using (true);

drop policy if exists "public can submit one vote" on public.votes;
create policy "public can submit one vote"
on public.votes
for insert
to anon
with check (
  choice in ('A','B','C','D')
  and char_length(device_id) between 20 and 100
);

-- 开启实时更新
alter publication supabase_realtime add table public.votes;
